// Content schemas. Pages import the parsed data from here, so invalid content fails the build.
import { z } from 'astro/zod';
import profileJson from '../../content/profile.json' with { type: 'json' };
import projectsJson from '../../content/projects.json' with { type: 'json' };
import aboutJson from '../../content/about.json' with { type: 'json' };
import booksJson from '../../content/books.json' with { type: 'json' };
import paintingsJson from '../../content/paintings.json' with { type: 'json' };
import galleryJson from '../../content/gallery.json' with { type: 'json' };
import filmsJson from '../../content/films.json' with { type: 'json' };
import learningJson from '../../content/learning.json' with { type: 'json' };
import caseStudiesJson from '../../content/case-studies.json' with { type: 'json' };
// Generated by the sync-blogs Action for the old site; read-only here.
import blogsJson from '../../../src/data/blogs.json' with { type: 'json' };

const text = z.string().trim().min(1);
const url = z.url({ protocol: /^https$/ });
const link = z.object({ label: text, url: z.union([url, z.string().regex(/^mailto:/)]) });
const rect = z
  .tuple([z.number(), z.number(), z.number(), z.number()])
  .refine(
    ([x, y, w, h]) => x >= 0 && y >= 0 && w > 0 && h > 0 && x + w <= 100 && y + h <= 100,
    'crop must lie inside the image'
  );
const localImage = z.string().regex(/^\/art\/[a-z0-9-]+\/[a-z0-9-]+\.webp$/);
const tag = z.enum(['doc', 'sch', 'deb', 'pro']);

export const ProfileSchema = z.object({
  name: text,
  jobTitle: text,
  summary: text,
  email: z.email(),
  location: text,
  links: z.array(link).min(1),
  languages: z.array(z.object({ name: text, level: text })),
  source: text,
});

export const ProjectSchema = z.object({
  id: z.string().regex(/^[a-z0-9-]+$/),
  title: text,
  flagship: z.boolean(),
  meta: text.optional(),
  summary: text,
  note: text.optional(),
  links: z.array(link).min(1),
  tags: z.array(text),
  /** Curated links to the owner's own posts about this project; each must be a post on /writing/. */
  writing: z.array(url).optional(),
});

// One editorial case study per flagship project (P04-T01). Every paragraph is drawn from `sources`.
export const CaseStudySchema = z.object({
  id: z.string().regex(/^[a-z0-9-]+$/),
  lede: text,
  verifiedOn: z.iso.date(),
  facts: z.array(z.object({ label: text, value: text })).min(1),
  sections: z.array(z.object({ heading: text, paras: z.array(text).min(1) })).min(2),
  limits: z.array(text).min(1),
  sources: z.array(z.object({ title: text, url })).min(1),
});

const entry = z.object({ title: text, org: text, start: text, end: text, summary: text });
const monthYear = z.string().regex(/^[A-Z][a-z]{2} \d{4}$/);
export const AboutSchema = z.object({
  roles: z.array(entry),
  education: z.array(entry),
  skills: z.array(z.object({ group: text, items: z.array(text).min(1) })).min(1),
  // Some certificates in the resume data carry only a year, or no date at all.
  certifications: z.array(
    z.object({
      name: text,
      issuer: text,
      date: z
        .string()
        .regex(/^([A-Z][a-z]{2} )?\d{4}$/)
        .nullable(),
      expires: monthYear.nullable(),
    })
  ),
  source: text,
});

export const BooksSchema = z.object({
  verifiedOn: z.iso.date(),
  source: text,
  stages: z
    .array(
      z.object({
        name: text,
        tagline: text, // the stage's key idea, shown as its title
        works: z
          .array(
            z.object({
              author: text,
              title: text,
              optional: z.boolean(),
              access: z.enum(['FREE', 'COMMERCIAL', 'BORROW']),
              url,
            })
          )
          .min(1),
      })
    )
    .min(1),
});

const crop = z.object({
  src: localImage,
  width: z.int().positive(),
  height: z.int().positive(),
  rect,
});
export const PaintingSchema = z.object({
  slug: z.string().regex(/^[a-z0-9-]+$/),
  n: z.int(),
  artist: text,
  title: text,
  note: text.nullable(),
  date: text,
  medium: text,
  dims: text,
  holder: text,
  holderRef: text,
  image: z.object({
    src: localImage,
    width: z.int().positive(),
    height: z.int().positive(),
    thumb: localImage,
    thumbWidth: z.int().positive(),
    thumbHeight: z.int().positive(),
    credit: text,
    source: text,
  }),
  look: text,
  details: z.array(crop.extend({ label: text, text })).min(1),
  context: z.array(z.object({ tag, label: text, text, source: text.nullable().optional() })),
  quote: z.object({ es: text, en: text, src: text, cite: text }).nullable(),
  readings: z
    .array(z.object({ tag, label: text, name: text, evidence: text, lit: text, open: text }))
    .min(1),
  extra: z.object({ tag, label: text, name: text, text }).nullable(),
  question: text,
  follow: z.array(text),
  counter: text,
  now: text,
  focus: crop.extend({ caption: text }),
  story: z.array(z.object({ kind: z.enum(['text', 'ret']), text })).optional(),
  technical: z.array(text).optional(),
  technicalNote: text.optional(),
  ladder: z.array(text).optional(),
  view: z.object({ label: text, u: url }).optional(),
  sources: z.array(z.object({ id: text, title: text, url })).min(1),
});

const BlogSchema = z.object({ title: text, link: url, date: text, source: text });

export const profile = ProfileSchema.parse(profileJson);
export const projects = z.array(ProjectSchema).parse(projectsJson);
const flagshipIds = projects.filter(p => p.flagship).map(p => p.id);
export const caseStudies = z
  .array(CaseStudySchema)
  .refine(
    cs =>
      cs
        .map(c => c.id)
        .sort()
        .join() === [...flagshipIds].sort().join(),
    'every flagship project has exactly one case study, and nothing else does'
  )
  .parse(caseStudiesJson);
export const caseStudyOf = (id: string) => caseStudies.find(c => c.id === id);
export const about = AboutSchema.parse(aboutJson);
export const books = BooksSchema.parse(booksJson);
export const paintings = z.array(PaintingSchema).parse(paintingsJson);

const slugs = new Set(paintings.map(p => p.slug));
const slug = z.string().refine(s => slugs.has(s), 'unknown painting');
export const GallerySchema = z
  .object({
    source: text,
    legend: z.array(z.object({ tag, label: text, text })),
    rooms: z.array(z.object({ numeral: text, name: text, sub: text, works: z.array(slug).min(1) })),
    pairs: z.array(z.object({ title: text, a: slug, b: slug, la: text, lb: text, q: text })),
  })
  .refine(
    g =>
      g.rooms
        .flatMap(r => r.works)
        .sort()
        .join() === [...slugs].sort().join(),
    'every painting sits in exactly one room'
  );
export const gallery = GallerySchema.parse(galleryJson);
export const paintingBySlug = (s: string) => paintings.find(p => p.slug === s)!;

// Essays on myth belong to the personal space; everything else is professional writing.
const MYTH = new Set(['the-absent-god', 'beyond-the-myth']);
export const posts = z
  .array(BlogSchema)
  .parse(blogsJson)
  .map(p => {
    const link = p.link.split('?')[0]; // drops Medium's RSS tracking parameter
    const date = new Date(p.date);
    return {
      title: p.title,
      link,
      source: p.source,
      date,
      myth: [...MYTH].some(m => link.includes(`/${m}`)),
    };
  })
  .sort((a, b) => +b.date - +a.date);

const postLinks = new Set(posts.map(p => p.link));
for (const p of projects)
  for (const w of p.writing ?? [])
    if (!postLinks.has(w)) throw new Error(`${p.id}: writing link ${w} is not a post on /writing/`);
export const postByLink = (link: string) => posts.find(p => p.link === link)!;

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
// A certificate counts as expired from the first day of the month after its expiry month.
export const isExpired = (expires: string | null, now = new Date()) => {
  if (!expires) return false;
  const [mon, year] = expires.split(' ');
  return now >= new Date(Number(year), MONTHS.indexOf(mon) + 1, 1);
};

export const monthYearOf = (d: Date) =>
  d.toLocaleDateString('en-GB', { month: 'long', year: 'numeric', timeZone: 'UTC' });

// The learning path (P05-T03). `lang` keeps the record locale-ready; only English ships.
export const LearningSchema = z.object({
  lang: z.literal('en'),
  intro: z.string(),
  steps: z
    .array(
      z.object({
        title: z.string(),
        why: z.string(),
        items: z
          .array(
            z.object({
              title: z.string(),
              url: z
                .string()
                .refine(
                  u => u.startsWith('/') || u.startsWith('https://'),
                  'site path or https URL'
                ),
              kind: z.string(),
              note: z.string().optional(),
            })
          )
          .min(1),
      })
    )
    .min(1),
});
export const learning = LearningSchema.parse(learningJson);

// Letterboxd diary entries synced from RSS
